"""Models for the chatterloop app.

Django's app registry imports `<app>.models` and nothing else, so a model
defined in another module is never registered. This file is what makes
`external_models` visible to the ORM.

The split is worth being able to see at a glance: everything imported from
`external_models` is a projection of a table `user_service` owns and Neon must
not migrate, while everything DEFINED below is Neon's own row, in Neon's own
database. `chatterloop/routers.py` enforces that split by model name.
"""

